import numpy as np
#For One Dimensional
zero_arrays_1D=np.zeros([3])
ones_arrays_1D=np.ones([3])
#For Two Dimensional
zero_arrays_2D=np.zeros([2,4])
ones_arrays_2D=np.ones([2,4])
print("Zero Arrays 1D: ",zero_arrays_1D)
print("Ones Arrays 1D: ",ones_arrays_1D)
print("Zero Arrays 2D: \n",zero_arrays_2D)
print("Ones Arrays 2D: \n",ones_arrays_2D)